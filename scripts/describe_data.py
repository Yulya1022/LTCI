    A(f'> {n - len(valid_year)} 条因页面未提供发布日期未纳入年度统计。')
    A('')

    # ---------- 三、层级与地区 ----------
    A('## 三、层级与地区分布')
    A('')
    A('| 文件层级 | 条数 | 占比 |')
    A('|---|---|---|')
    for k, v in df['文件层级'].value_counts().items():
        A(f'| {k} | {v} | {v/n*100:.1f}% |')
    A('')
