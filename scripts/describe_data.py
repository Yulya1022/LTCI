    A('')

    # ---------- 六、文本特征 ----------
    A('## 六、文本特征')
    A('')
    lens = df['政策原文'].fillna('').str.len()
    A('| 指标 | 全量 | 政策文件子集 |')
    A('|---|---|---|')
    sub_lens = sub['政策原文'].fillna('').str.len()
    A(f'| 条数 | {len(df)} | {len(sub)} |')
    A(f'| 平均字数 | {lens.mean():.0f} | {sub_lens.mean():.0f} |')
    A(f'| 中位字数 | {lens.median():.0f} | {sub_lens.median():.0f} |')
