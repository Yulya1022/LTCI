PILOT = set(config.PILOT_BATCH1) | set(config.PILOT_BATCH2)
EXTRA = set(config.EXTRA_CITIES)
PROVS = set(config.PROVINCES)


def to_province(r):
    if r == '国家层面':
        return '国家层面'
    if r in PROVS:
        return r
    return CITY_PROV.get(r, '待识别')


def issuer_type(s):
    if not isinstance(s, str) or not s.strip():
        return '未标注'
    if re.search(r'[\s　、]', s.strip()):
        return '多部门联合发文'
    for kw, name in [('医疗保障局', '医保局'), ('医保局', '医保局'), ('人民政府', '政府'),
                     ('政府办公室', '政府'), ('人力资源和社会保障', '人社'), ('人社', '人社'),
                     ('卫生健康', '卫健'), ('民政', '民政'), ('财政', '财政'), ('发展改革', '发改')]:
        if kw in s:
            return name
    return '其他机构'


def main():
    df = pd.read_csv(os.path.join(config.PROCESSED_DIR, 'ltci_policies_all.csv'))
    sub = df[df['文件类型'] == '政策文件'].copy()
